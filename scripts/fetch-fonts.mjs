/**
 * Downloads the latin subsets of the three families the design system names
 * (Newsreader, IBM Plex Sans, IBM Plex Mono) into public/fonts/, and writes
 * public/fonts/fonts.css for the document to link.
 *
 * Runtime font requests are forbidden by DESIGN-SYSTEM.md §3, so this script is
 * the only thing that ever talks to a font CDN. Run once: `npm run fonts`.
 */
import { mkdir, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'

const UA =
  'Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/126.0 Safari/537.36'

const FAMILIES = [
  {
    query: 'Newsreader:ital,opsz,wght@0,6..72,400;0,6..72,500;0,6..72,600;1,6..72,400',
    family: 'Newsreader',
    slug: 'newsreader',
  },
  {
    query: 'IBM+Plex+Sans:wght@400;500;600;700',
    family: 'IBM Plex Sans',
    slug: 'plex-sans',
  },
  {
    query: 'IBM+Plex+Mono:wght@400;500',
    family: 'IBM Plex Mono',
    slug: 'plex-mono',
  },
]

const OUT_DIR = resolve(process.cwd(), 'public/fonts')

await mkdir(OUT_DIR, { recursive: true })

const cssUrl = `https://fonts.googleapis.com/css2?${FAMILIES.map(
  (f) => `family=${f.query}`,
).join('&')}&display=swap`

const css = await fetch(cssUrl, { headers: { 'User-Agent': UA } }).then((r) => {
  if (!r.ok) throw new Error(`Google Fonts responded ${r.status}`)
  return r.text()
})

// Split into @font-face blocks that carry the `/* latin */` marker.
const blocks = css.split('/* latin */').slice(1)
if (blocks.length === 0) throw new Error('No latin subsets found in the font CSS.')

const seen = new Map()
const faces = []

for (const block of blocks) {
  const face = block.slice(0, block.indexOf('}') + 1)
  const url = face.match(/url\((https:\/\/[^)]+\.woff2)\)/)?.[1]
  const family = face.match(/font-family:\s*'([^']+)'/)?.[1]
  const style = face.match(/font-style:\s*([a-z]+)/)?.[1] ?? 'normal'
  const weight = face.match(/font-weight:\s*([0-9 ]+);/)?.[1]?.trim() ?? '400'
  const display = face.match(/font-display:\s*([a-z]+)/)?.[1] ?? 'swap'
  const unicodeRange = face.match(/unicode-range:\s*([^;]+);/)?.[1] ?? ''
  const stretch = face.match(/font-stretch:\s*([^;]+);/)?.[1] ?? ''

  if (!url || !family) continue
  const meta = FAMILIES.find((f) => f.family === family)
  if (!meta) continue

  let filename = seen.get(url)
  if (!filename) {
    filename = `${meta.slug}-${weight.replace(/\s+/g, '-')}${style === 'italic' ? '-italic' : ''}.woff2`
    seen.set(url, filename)
    const bytes = await fetch(url, { headers: { 'User-Agent': UA } }).then((r) => {
      if (!r.ok) throw new Error(`Font download failed ${r.status} for ${url}`)
      return r.arrayBuffer()
    })
    await writeFile(resolve(OUT_DIR, filename), Buffer.from(bytes))
    console.log(`  ${filename}  ${(bytes.byteLength / 1024).toFixed(1)} KB`)
  }

  faces.push({
    family,
    style,
    weight,
    display,
    unicodeRange,
    stretch,
    filename,
  })
}

const rules = faces
  .map(
    (f) => `@font-face {
  font-family: '${f.family}';
  font-style: ${f.style};
  font-weight: ${f.weight};
  font-display: ${f.display};${f.stretch ? `\n  font-stretch: ${f.stretch};` : ''}
  src: url('/fonts/${f.filename}') format('woff2');${
    f.unicodeRange ? `\n  unicode-range: ${f.unicodeRange};` : ''
  }
}`,
  )
  .join('\n\n')

await mkdir(OUT_DIR, { recursive: true })
await writeFile(
  resolve(OUT_DIR, 'fonts.css'),
  `/* Generated by scripts/fetch-fonts.mjs. Self-hosted latin subsets. Do not edit by hand. */\n\n${rules}\n`,
)

console.log(`\nWrote ${faces.length} @font-face rules and ${seen.size} files to public/fonts/.`)
